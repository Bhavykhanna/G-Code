/**
 * check-validate.js -- the safety gate's portable rules.
 *   node test/check-validate.js
 *
 * Synthetic files only, so this runs anywhere. It pins the two rules that were
 * wrong on 2026-09-19 (public B14, B15) and the hole found while fixing them,
 * because all three were invisible until someone opened a file from another
 * printer:
 *
 *   - the end sequence an EDIT must keep is the one the SOURCE FILE had, not a
 *     list of this machine's markers. Same strictness here, correct elsewhere.
 *   - the check must not read the CONFIG_BLOCK, which quotes machine_end_gcode
 *     verbatim -- a file whose real ending was deleted used to pass.
 *   - a missing `machine_max_speed_x` must not turn the feedrate limit into 0.
 *
 * It also checks the standalone form, which is what a fresh slice is validated
 * with: no source to compare against, so the file only has to shut the machine
 * down at all.
 */
import { validate } from '../server/api/validate.js';
import { parseGcode } from '../src/parser/parse.js';

let fails = 0;
const ok = (name, cond, detail = '') => {
  if (!cond) fails++;
  console.log('  ' + (cond ? 'ok  ' : 'FAIL') + '  ' + name.padEnd(62) + detail);
};
const has = (v, code) => v.errors.some((e) => e.code === code);
const codes = (v) => v.errors.map((e) => e.code).join(',') || '(none)';

const NL = String.fromCharCode(10);
const j = (...lines) => lines.flat().join(NL) + NL;

/** A minimal but complete print, in the dialect of one machine. */
function print({ ending, config = {}, body = null, extra = [], configEnding = null }) {
  const cfg = {
    bed_shape: '0x0,220x0,220x220,0x220',
    printable_height: '250',
    ...config,
  };
  return j(
    '; generated by TestSlicer 1.0',
    'M83',
    'M104 S210',
    'M109 S210',
    ';LAYER:0',
    ';Z:0.2',
    ';TYPE:Outer wall',
    ';WIDTH:0.45',
    ';HEIGHT:0.2',
    body || [
      'G1 X20 Y20 Z0.2 F1800',
      'G1 X40 Y20 E1.2 F1800',
      'G1 X40 Y40 E1.2',
      'G1 X20 Y40 E1.2',
      'G1 E-0.8 F2100',
      'G1 E0.8 F2100',
    ],
    extra,
    ending,
    '; CONFIG_BLOCK_START',
    Object.entries(cfg).map(([k, v]) => `; ${k} = ${v}`),
    // The trap: the settings dump quotes the end G-code, markers and all.
    '; machine_end_gcode = ' + (configEnding || ending).join(' ; '),
    '; CONFIG_BLOCK_END',
  );
}

/** This machine's ending. */
const MINE = [';PRINT_END', 'M104 S0', 'M140 S0', 'M84', '; EXECUTABLE_BLOCK_END'];
/** A Marlin printer's ending -- different words, same job. */
const MARLIN = ['M104 S0', 'M140 S0', 'M18', ';End of Gcode'];

console.log('\n=== an edit keeps the ending the source file had ===');
{
  for (const [label, ending] of [['this machine', MINE], ['a Marlin printer', MARLIN]]) {
    const src = print({ ending });
    const good = validate(src, { original: parseGcode(src), originalText: src });
    ok(`${label}: an unchanged file passes`, !has(good, 'END_SEQUENCE'), codes(good));

    // Drop one marker from the executable part, leaving the config dump intact.
    for (const marker of ending) {
      const broken = print({ ending: ending.filter((m) => m !== marker) });
      const v = validate(broken, { original: parseGcode(src), originalText: src });
      ok(`${label}: dropping ${marker} is refused`, has(v, 'END_SEQUENCE'),
        v.errors.filter((e) => e.code === 'END_SEQUENCE').map((e) => e.message)[0] || '');
    }
  }
}

console.log('\n=== the CONFIG_BLOCK cannot satisfy the check ===');
{
  // Every marker is still in the settings dump; none is in the print itself.
  const src = print({ ending: MINE });
  // Nothing executable is left, but the settings dump still quotes all of it.
  const gutted = print({ ending: [], configEnding: MINE });
  const v = validate(gutted, { original: parseGcode(src), originalText: src });
  ok('a file whose real ending was deleted is refused', has(v, 'END_SEQUENCE'), codes(v));
  ok('and the markers ARE still present in the text', MINE.every((m) => gutted.includes(m)),
    'so only cutting at CONFIG_BLOCK_START can catch this');
  const standalone = validate(gutted);
  ok('standalone too -- no hotend off, no steppers off', has(standalone, 'END_SEQUENCE'), codes(standalone));
}

console.log('\n=== standalone: only "does it shut the machine down" ===');
{
  const marlin = validate(print({ ending: MARLIN }));
  ok('a Marlin ending is accepted on its own', !has(marlin, 'END_SEQUENCE'), codes(marlin));
  ok('and its markers are reported', (marlin.stats.endMarkers || []).includes('M18'),
    (marlin.stats.endMarkers || []).join(' '));

  const klipper = validate(print({ ending: ['TURN_OFF_HEATERS', 'M84'] }));
  ok('so is TURN_OFF_HEATERS + M84', !has(klipper, 'END_SEQUENCE'), codes(klipper));
  ok('with a warning that the bed is not turned off',
    klipper.warnings.some((w) => w.code === 'END_SEQUENCE'),
    klipper.warnings.map((w) => w.code).join(',') || '(none)');

  const none = validate(print({ ending: ['; the end'] }));
  ok('a file that never turns anything off is refused', has(none, 'END_SEQUENCE'), codes(none));
}

console.log('\n=== B14: a file with no machine_max_speed_x ===');
{
  const v = validate(print({ ending: MINE }));
  ok('the feedrate limit falls back to the default, not 0', v.limits.maxFeedMmMin === 500 * 60,
    v.limits.maxFeedMmMin + ' mm/min');
  ok('so no move is reported as too fast', !has(v, 'BAD_FEEDRATE'), codes(v));

  const withKey = validate(print({ ending: MINE, config: { machine_max_speed_x: '300,300' } }));
  ok('and a real value is still used', withKey.limits.maxFeedMmMin === 300 * 60,
    withKey.limits.maxFeedMmMin + ' mm/min');
  const empty = validate(print({ ending: MINE, config: { machine_max_speed_x: '' } }));
  ok('an empty value does not mean zero either', empty.limits.maxFeedMmMin === 500 * 60,
    empty.limits.maxFeedMmMin + ' mm/min');
}

console.log('\n=== the envelope still comes from the file ===');
{
  const v = validate(print({ ending: MINE }));
  ok('bed from bed_shape', v.limits.bedX === 220 && v.limits.bedY === 220, `${v.limits.bedX} x ${v.limits.bedY}`);
  ok('height from printable_height', v.limits.maxZ === 250, String(v.limits.maxZ));
  const off = validate(print({ ending: MINE, extra: ['G1 X400 Y20 E1 F1800'] }));
  ok('a move outside that bed is refused', has(off, 'OUT_OF_BOUNDS') || has(off, 'ENVELOPE'), codes(off));
}

console.log(fails ? `\n  ${fails} check(s) FAILED\n` : '\n  all checks passed\n');
process.exit(fails ? 1 : 0);
