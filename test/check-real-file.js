/**
 * Parse a real G-code file and cross-check the result against the numbers the
 * slicer itself wrote into the footer. If our extrusion total matches the
 * slicer's "filament used [mm]", the geometry pass is reading the file right.
 *
 *   node test/check-real-file.js [path-to.gcode]
 */
import { readFileSync } from 'node:fs';
import { argv } from 'node:process';
import { parseGcode, KIND, FEATURE_NAMES, formatDuration, segLength } from '../src/parser/parse.js';

const file = argv[2] || '../phonecase-17pro/old/EN4Max_0.4_Iphone17Pro_HexCover_HSPLA+_0.20_v1-ironed_49m.gcode';

const text = readFileSync(file, 'utf8');
const t0 = performance.now();
const r = parseGcode(text);
const ms = performance.now() - t0;

const seg = r.segments;
let extrudeE = 0, retractE = 0, primeE = 0, extrudeDist = 0, travelDist = 0;
const byFeature = new Map();
for (let i = 0; i < r.count; i++) {
  const k = seg.kind[i];
  const len = segLength(seg, i);
  if (k === KIND.EXTRUDE) {
    extrudeE += seg.e[i];
    extrudeDist += len;
    const f = FEATURE_NAMES[seg.feature[i]];
    const acc = byFeature.get(f) || { mm: 0, sec: 0, n: 0 };
    acc.mm += len; acc.sec += seg.time[i]; acc.n++;
    byFeature.set(f, acc);
  } else if (k === KIND.TRAVEL) {
    travelDist += len;
    if (seg.e[i] < 0) retractE += seg.e[i]; // retract while wiping/travelling
  } else if (k === KIND.RETRACT) {
    retractE += seg.e[i];
  } else if (k === KIND.PRIME) {
    primeE += seg.e[i];
  }
}

// The slicer's "filament used" is the material actually deposited, so it is the
// sum of E over extruding moves alone. Retractions are cancelled out by the
// matching re-prime moves and must not be subtracted here.
const expected = r.meta.filamentUsedMm;
const errPct = expected ? ((extrudeE - expected) / expected) * 100 : NaN;

const row = (k, v) => console.log('  ' + k.padEnd(26) + v);

console.log('\n=== ' + file.split(/[\\/]/).pop() + ' ===');
row('parse time', ms.toFixed(0) + ' ms');
row('generator', r.meta.generator.replace('generated by ', ''));
row('moves', r.count.toLocaleString());
row('source lines', r.meta.lineCount.toLocaleString());
row('layers parsed', r.layers.length + '  (header says ' + r.meta.layerCount + ')');
row('relative E (M83)', r.relativeE ? 'yes' : 'NO -- editing disabled');
row('config keys', Object.keys(r.config).length);
row('time-model scale', r.timeScale.toFixed(3) + '  (our estimate vs slicer)');

console.log('\n  -- cross-check against the slicer\'s own footer --');
row('deposited, ours', extrudeE.toFixed(2) + ' mm');
row('deposited, slicer', expected.toFixed(2) + ' mm');
row('error', errPct.toFixed(4) + ' %   ' + (Math.abs(errPct) < 0.05 ? 'OK' : 'MISMATCH'));
row('retract / prime', retractE.toFixed(1) + ' / +' + primeE.toFixed(1) + ' mm');
row('print time, slicer', r.meta.estimatedTimeText + ' (' + r.meta.estimatedTimeSec + 's)');
row('weight, slicer', r.meta.filamentUsedG + ' g');

console.log('\n  -- geometry --');
row('extruded path', (extrudeDist / 1000).toFixed(2) + ' m');
row('travel', (travelDist / 1000).toFixed(2) + ' m');
row('retractions', seg.kind.reduce((a, k) => a + (k === KIND.RETRACT ? 1 : 0), 0));
row('bed', r.meta.bedShape ? r.meta.bedShape.map((p) => p.join('x')).join(' ') : '?');
row('max Z', r.meta.maxZ + ' mm');

console.log('\n  -- time and length by feature --');
const total = [...byFeature.values()].reduce((a, b) => a + b.sec, 0);
const sorted = [...byFeature.entries()].sort((a, b) => b[1].sec - a[1].sec);
for (const [name, v] of sorted) {
  console.log(
    '  ' + name.padEnd(24) +
    formatDuration(v.sec).padStart(8) +
    ((v.sec / total) * 100).toFixed(1).padStart(7) + '%' +
    (v.mm / 1000).toFixed(2).padStart(9) + ' m' +
    v.n.toLocaleString().padStart(10) + ' moves'
  );
}

if (r.warnings.length) {
  console.log('\n  -- warnings --');
  for (const w of r.warnings) console.log('  ! ' + w);
}
console.log();
